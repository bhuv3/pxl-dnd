# Packs a character's rotation PNGs into a JS file of data URLs (canvas can read those on file://).
# Usage: python3 tools/map-editor/pack_character.py art/map-editor/elf-wizard "Elf wizard"
# Writes map-editor/assets/characters/<folder name>.js, which the editor loads.
import base64, json, os, sys

folder, name = sys.argv[1], sys.argv[2]
key = os.path.basename(folder.rstrip('/'))
dirs = ['south', 'south-east', 'east', 'north-east', 'north', 'north-west', 'west', 'south-west']
rot = {}
for d in dirs:
    with open(os.path.join(folder, d + '.png'), 'rb') as f:
        rot[d] = 'data:image/png;base64,' + base64.b64encode(f.read()).decode()
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'map-editor', 'assets', 'characters', key + '.js')
with open(out, 'w') as f:
    f.write('// Generated by tools/map-editor/pack_character.py from %s/. Do not edit.\n' % key)
    f.write('CharacterArt.add(%s, %s, %s);\n' % (json.dumps(key), json.dumps(name), json.dumps(rot, indent=2)))
print('wrote', out)
